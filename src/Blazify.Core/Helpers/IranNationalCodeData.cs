    public static NationalCodeLocation Resolve(string? nationalCode)
    {
        var digits = new string((nationalCode ?? "").Where(char.IsDigit).ToArray());
        if (digits.Length < 3) return new("", "نامشخص");
        return Map.TryGetValue(digits[..3], out var loc) ? loc : new("", "نامشخص");
    }
